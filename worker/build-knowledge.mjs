// Turns the published pages into plain text for Valentino's system prompt.
// The GitHub Action runs it on every push and uploads knowledge.txt to Workers KV, where the worker reads it.
// knowledge.js is the same text bundled into the worker as a fallback; it refreshes whenever the worker is deployed.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PAGES = [
  "index.html", "about.html", "fun.html",
  "projects/mensio.html", "projects/deploy-design-system.html", "projects/denials.html", "projects/automl.html",
  "projects/ctrlz.html", "projects/bumpy.html", "projects/somnia.html", "projects/coverflow.html",
];

const text = (html) => html
  .replace(/<!--[\s\S]*?-->/g, "")                        // internal notes stay out
  .replace(/<(script|style|svg|noscript|template)[\s\S]*?<\/\1>/gi, "")
  .replace(/<(header|footer|nav)\b[\s\S]*?<\/\1>/gi, "")  // site chrome, same on every page
  .replace(/<img\b[^>]*\balt="([^"]+)"[^>]*>/gi, " [image: $1] ")
  .replace(/<h([1-4])\b[^>]*>/gi, (_, n) => `\n\n${"#".repeat(+n)} `)
  .replace(/<\/h[1-4]>/gi, "\n")
  .replace(/<li\b[^>]*>/gi, "\n- ")
  .replace(/<(p|div|section|figure|figcaption|tr|br|blockquote)\b[^>]*>/gi, "\n")
  .replace(/<[^>]+>/g, " ")
  .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
  .replace(/&quot;/g, '"').replace(/&#39;|&rsquo;/g, "’").replace(/&ldquo;|&rdquo;/g, '"').replace(/&mdash;/g, "—").replace(/&ndash;/g, "–").replace(/&times;/g, "×")
  .replace(/[ \t]+/g, " ")
  .replace(/ *\n */g, "\n")
  .replace(/\n{3,}/g, "\n\n")
  .trim();

// Valentino's scripted answers are Anoushka's own words, and cover facts the pages don't (Kolkata, food, the cats)
const chat = readFileSync(path.join(root, "chat.js"), "utf8");
const topicsSrc = chat.slice(chat.indexOf("const TOPICS = ["), chat.indexOf("\n  ];", chat.indexOf("const TOPICS = [")) + 5);
const consts = [...chat.matchAll(/^  const (CAL|LINKEDIN|EMAIL|GITHUB|BEHANCE|RESUME|START|CAT) = .*;$/gm)].map((m) => m[0]).join("\n");
const link = (href, label) => `[${label}](${href})`;
const TOPICS = new Function("link", `${consts}\n${topicsSrc}\nreturn TOPICS;`)(link);
const answers = TOPICS.map((t) => `- On ${t.keys.slice(0, 4).join(", ")}: ${t.html.replace(/<[^>]+>/g, "")}`).join("\n");

const out = [
  ...PAGES.map((p) => `<page path="${p}">\n${text(readFileSync(path.join(root, p), "utf8"))}\n</page>`),
  `<scripted_answers note="Anoushka's own answers, written for Valentino">\n${answers}\n</scripted_answers>`,
  // Facts she has confirmed that aren't on the pages. Edit worker/facts.md to add more.
  `<facts>\n${readFileSync(path.join(root, "worker/facts.md"), "utf8").trim()}\n</facts>`,
].join("\n\n");
writeFileSync(path.join(root, "worker/knowledge.txt"), out);
writeFileSync(path.join(root, "worker/src/knowledge.js"), `// Generated by build-knowledge.mjs. Do not edit by hand.\nexport default ${JSON.stringify(out)};\n`);
console.log(`${PAGES.length} pages + ${TOPICS.length} answers, ${out.length} characters`);
